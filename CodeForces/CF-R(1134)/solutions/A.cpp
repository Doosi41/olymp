// Codeforces Round 1134 (Div. 4) · A · Три кучки
//
// Есть три кучки камней: a, b, c. Нужно сделать РОВНО один ход: взять один камень из какой-то
// кучки и положить в одну из двух других. Нельзя пропустить ход и нельзя сделать больше одного.
// Определить, может ли после этого хода во всех трёх кучках стать одинаковое количество камней.
//
// Входные данные: t (1 ≤ t ≤ 1000) наборов. В каждом — a, b, c (1 ≤ a ≤ b ≤ c ≤ 10).
// Выходные данные: YES или NO для каждого набора.
//
// Пример:
//   6 / 1 2 3 / 2 2 2 / 3 4 5 / 1 1 4 / 8 9 10 / 3 5 7
//   → YES / NO / YES / NO / YES / NO

#include <iostream>

using namespace std;

bool ok(int x, int y, int z) {
    if (z - 1 == y && x + 1 == y){
        return true;
    } else {
        return false;
    }
}

int main() {

    int k;
    cin >> k;

    int a, b, c;

    for (int i = 0; i < k; i++) {
        cin >> a >> b >> c;
        
        if (ok(a, b, c)) {
            cout << "YES" << endl;
        } else {
            cout << "NO" << endl;
        }
    }
    return 0;
}