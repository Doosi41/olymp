// Лесенкой называется набор кубиков, в котором каждый более верхний слой содержит кубиков
// меньше, чем предыдущий. Требуется написать программу, вычисляющую число лесенок, которое
// можно построить из N кубиков.
//
// Входные данные: во входном файле INPUT.TXT записано натуральное число N (1 ≤ N ≤ 100) –
// количество кубиков в лесенке.
//
// Выходные данные: в выходной файл OUTPUT.TXT необходимо вывести число лесенок, которые
// можно построить из N кубиков.
//
// Примеры:
//   3 → 2
//   6 → 4

#include <iostream>
#include <vector>

using namespace std;

int main() {
    int n;
    cin >> n;

    vector<long long> ways(n + 1, 0);
    ways[0] = 1;

    // Каждая ступень имеет уникальную высоту, поэтому это разбиения n на разные слагаемые.
    for (int height = 1; height <= n; ++height) {
        for (int sum = n; sum >= height; --sum) {
            ways[sum] += ways[sum - height];
        }
    }

    cout << ways[n] << '\n';
}
