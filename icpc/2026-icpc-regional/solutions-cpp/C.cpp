// Ограничения: 2 с, 256 МБ
//
// S(x) — сумма цифр строки x. Из числа N0 (K цифр, без ведущих нулей) строим N1: для каждой пары
// L ≤ R берём подотрезок цифр N0[L..R] и складываем S(N0[L..R]) по всем таким парам. Так же из N1
// строится N2, из N2 — N3 и так далее. Числовой КОРНИЩЕ числа N0 — минимальное число во всей
// последовательности N0, N1, N2, …
//
// Над числом N выполняют Q запросов: i-й запрос меняет цифру на позиции Pi на Di (изменения
// сохраняются, ведущий ноль не появляется). Нужно вывести КОРНИЩЕ исходного числа и после
// каждого запроса.
//
// Входные данные: K (1 ≤ K ≤ 2·10^5); K цифр числа N; Q (1 ≤ Q ≤ 2·10^5); Q чисел P1 … PQ
// (1 ≤ Pi ≤ K); Q чисел D1 … DQ (0 ≤ Di ≤ 9). Если Pi = 1, то Di ≥ 1.
// Выходные данные: Q + 1 чисел R0 … RQ (0 ≤ Ri ≤ 10^18) в одной строке через пробел.
//
// Пример (« / » — переход на новую строку):
//   5 / 14974 / 4 / 1 2 1 4 / 3 7 7 0 → 6 18 8 4 18
//
// Разбор примера: 14974 → 194 → 51 → 12 → 6 → 6 …, минимум 6.
// После запросов: 34974 → 204 → 18 → 18 … (18); 37974 → 228 → 38 → 22 → 8 … (8);
// 77974 → 248 → 46 → 20 → 4 … (4); 77904 → 192 → 45 → 18 → 18 … (18).

#include <iostream>
#include <vector>
#include <string>

using namespace std;

int main() {
    int k;
    string s;
    cin >> k >> s;          // k = 5, s = "14974"

    vector<int> digit(k);
    for (int i = 0; i < k; i++) {
        digit[i] = s[i] - '0';   // символ '1' → число 1
    }



}
