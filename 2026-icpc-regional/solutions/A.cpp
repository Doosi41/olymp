// Ограничения: 1 с, 256 МБ
//
// Берём целое положительное n. Пока n не равно единице: если n чётно — делим его на 2, если
// нечётно — возводим в квадрат и прибавляем единицу. Определить, превратится ли n в единицу
// за конечное число шагов.
//
// Входные данные: одно целое число n (1 ≤ n ≤ 10^9).
// Выходные данные: «YES», если n превращается в единицу за конечное число шагов, и «NO» в
// противном случае. Ответ всегда существует и единственен.
//
// Примеры (« / » — переход на новую строку):
//   1 → YES
//   17 → NO
//   4 → YES

#include <iostream>

using namespace std;

int main() {
    int x;
    cin >> x;

    while (x%2==0) {
        x = x/2;
    }
    if (x == 1) {
        cout << "YES";
    }
    
    else {
        cout << "NO";
    }
}
